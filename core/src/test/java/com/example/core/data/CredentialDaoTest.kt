package com.example.core.data

import android.app.Application
import androidx.room.Room
import com.example.core.data.entity.EncryptedCredentialEntity
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.launch
import kotlinx.coroutines.runBlocking
import org.junit.*
import org.junit.Assert.*
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [28], application = Application::class)
class CredentialDaoTest {
    private lateinit var db: VaultDatabase
    private val dao
        get() = db.credentialDao()

    @Before
    fun setup() {
        db =
            Room.inMemoryDatabaseBuilder(
                    RuntimeEnvironment.getApplication(),
                    VaultDatabase::class.java,
                )
                .allowMainThreadQueries()
                .build()
    }

    @After
    fun close() {
        db.close()
    }

    private fun row(id: Int = 0) =
        EncryptedCredentialEntity(
            id,
            "Google",
            "cipher-user",
            "iv-user",
            "cipher-pass",
            "iv-pass",
            "url",
            2,
        )

    @Test
    fun emptyDatabaseEmitsEmptyList() = runBlocking {
        assertTrue(dao.getAllCredentials().first().isEmpty())
    }

    @Test fun missingIdReturnsNull() = runBlocking { assertNull(dao.getCredentialById(99)) }

    @Test
    fun insertAssignsPositiveIdAndPreservesEveryField() = runBlocking {
        dao.insertCredential(row())
        val saved = dao.getAllCredentials().first().single()
        assertTrue(saved.id > 0)
        assertEquals(row(saved.id), saved)
        assertEquals(saved, dao.getCredentialById(saved.id))
    }

    @Test
    fun autoGeneratedIdsAreDistinct() = runBlocking {
        repeat(3) { dao.insertCredential(row()) }
        assertEquals(3, dao.getAllCredentials().first().map { it.id }.distinct().size)
    }

    @Test
    fun explicitIdIsPreserved() = runBlocking {
        dao.insertCredential(row(41))
        assertEquals(row(41), dao.getCredentialById(41))
    }

    @Test
    fun sameIdReplacesAllFieldsWithoutCreatingSecondRow() = runBlocking {
        dao.insertCredential(row(1))
        val changed =
            row(1)
                .copy(
                    platformName = "Bank",
                    encryptedUsername = "new-user",
                    usernameIv = "new-iv",
                    encryptedPassword = "new-pass",
                    passwordIv = "new-pass-iv",
                    website = "other",
                    categoryId = 4,
                )
        dao.insertCredential(changed)
        assertEquals(listOf(changed), dao.getAllCredentials().first())
    }

    @Test
    fun deleteOnlyRemovesRequestedRecord() = runBlocking {
        dao.insertCredential(row(1))
        dao.insertCredential(row(2))
        dao.deleteCredential(1)
        assertNull(dao.getCredentialById(1))
        assertEquals(listOf(row(2)), dao.getAllCredentials().first())
    }

    @Test
    fun deletingUnknownIdIsNoOp() = runBlocking {
        dao.insertCredential(row(1))
        dao.deleteCredential(99)
        assertEquals(listOf(row(1)), dao.getAllCredentials().first())
    }

    @Test
    fun repeatedDeleteIsSafe() = runBlocking {
        dao.insertCredential(row(1))
        dao.deleteCredential(1)
        dao.deleteCredential(1)
        assertTrue(dao.getAllCredentials().first().isEmpty())
    }

    @Test
    fun unicodeEmptyFieldsAndLargePayloadRoundTrip() = runBlocking {
        val r =
            row(1)
                .copy(
                    platformName = "שלום 🔐",
                    encryptedUsername = "",
                    website = "",
                    encryptedPassword = "x".repeat(100000),
                )
        dao.insertCredential(r)
        assertEquals(r, dao.getCredentialById(1))
    }

    @Test
    fun dataIsNotAccessibleAfterClose() {
        db.close()
        assertFalse(db.isOpen)
    }

    @Test
    fun activeFlowObservesInsertAndDelete() =
        runBlocking<Unit> {
            val changes =
                kotlinx.coroutines.channels.Channel<List<EncryptedCredentialEntity>>(
                    kotlinx.coroutines.channels.Channel.UNLIMITED
                )
            val job = launch { dao.getAllCredentials().collect { changes.send(it) } }
            try {
                assertTrue(kotlinx.coroutines.withTimeout(5000) { changes.receive() }.isEmpty())
                dao.insertCredential(row(1))
                val inserted =
                    kotlinx.coroutines.withTimeout(5000) {
                        var value = changes.receive()
                        while (value.isEmpty()) value = changes.receive()
                        value
                    }
                assertEquals(listOf(row(1)), inserted)
                dao.deleteCredential(1)
                val deleted =
                    kotlinx.coroutines.withTimeout(5000) {
                        var value = changes.receive()
                        while (value.isNotEmpty()) value = changes.receive()
                        value
                    }
                assertTrue(deleted.isEmpty())
            } finally {
                job.cancel()
                changes.close()
            }
        }
}
